"""Build data/videos.js from tools/playlist.tsv (id<TAB>title).
Main list = Day 1..365 in day order (playlist order is scrambled).
Extras (no day number, or a repeated day) go at the end with their own titles."""
import re, json
rows = [l.rstrip("\n").split("\t") for l in open("tools/playlist.tsv", encoding="utf8")]
main, extras, seen = {}, [], set()
for id_, t in rows:
    m = re.search(r"Day\s*(\d+)", t, re.I)
    d = int(m.group(1)) if m else None
    if d and d not in main and id_ != "o7uQvU7tk8U":  # o7uQvU7tk8U: duplicate Day 222 upload, same 5:12 length
        main[d] = id_
    else:
        extras.append({"id": id_, "title": t})
assert sorted(main) == list(range(1, 366))
videos = [{"id": main[d], "title": f"Day {d}", "day": d} for d in range(1, 366)] + extras
open("data/videos.js", "w", encoding="utf8").write(
    "// Generated by tools/build-videos.py. Days 1-365 in order, then extras.\nexport default "
    + json.dumps(videos, ensure_ascii=False, indent=0).replace("\n", "") + ";\n")
print(len(videos), "videos,", len(extras), "extras")
