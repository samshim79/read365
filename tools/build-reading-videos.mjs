// Builds data/reading-videos.js from tools/reading-videos.json.
// The JSON is keyed by book number (1 = Genesis ... 66 = Revelation); each entry lists that book's chapters in order
// as "videoId:seconds". Source: the 공동체성경읽기 channel's "NN. <book>_장별 구절 영상(개역개정)" playlists (CGNTV / PRS).
// Old Testament books come from the same channel's "N. <book>_장별 구절 영상(개역개정)" playlists where they exist; chapters
// missing from a playlist (and books with no playlist, e.g. 룻기, 요엘, 요나) were found by searching for "<book> N장 (개역개정)"
// on the channel and checking the original title. 스가랴 12장 has no (개역개정) video, so it uses the channel's illustrated
// "스가랴 12장" (개역개정 wording, bilingual).
import { readFileSync, writeFileSync } from 'node:fs';

const BOOKS = ('GEN EXO LEV NUM DEU JOS JDG RUT 1SA 2SA 1KI 2KI 1CH 2CH EZR NEH EST JOB PSA PRO ECC SNG ISA JER LAM EZK DAN '
  + 'HOS JOL AMO OBA JON MIC NAM HAB ZEP HAG ZEC MAL MAT MRK LUK JHN ACT ROM 1CO 2CO GAL EPH PHP COL 1TH 2TH 1TI 2TI TIT PHM '
  + 'HEB JAS 1PE 2PE 1JN 2JN 3JN JUD REV').split(' ');
// ESV: Crossway's "ESV Bible Audio" channel, one playlist per book ("<Book> - English Standard Version"), one video per
// chapter, checked by title (a mislabelled "Job 3" upload is Job 23; duplicate uploads of John 8 and 21 use the ESV-titled one).
const SETS = [
  ['reading-videos.json', 'reading-videos.js', '공동체성경읽기 chapter videos (개역개정)'],
  ['reading-videos-esv.json', 'reading-videos-esv.js', 'ESV Bible Audio (Crossway) chapter videos'],
];
for (const [from, to, what] of SETS) {
  const src = JSON.parse(readFileSync(new URL(`./${from}`, import.meta.url), 'utf8'));
  const out = {};
  for (const [num, chapters] of Object.entries(src)) out[BOOKS[num - 1]] = chapters;
  writeFileSync(new URL(`../data/${to}`, import.meta.url),
    '// Generated by tools/build-reading-videos.mjs. Do not edit by hand.\n'
    + `// { USFM book: ["videoId:seconds" for chapter 1, chapter 2, ...] }, ${what}.\n`
    + `export default ${JSON.stringify(out)};\n`);
  console.log(to, Object.keys(out).length, 'books,', Object.values(out).flat().length, 'chapters');
}
