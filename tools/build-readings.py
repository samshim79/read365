"""Build data/readings.js from tools/readings.tsv (day<TAB>reading, copied from the Notion schedules).
Each reading becomes a list of [label, OSIS reference] chips. A chip opens the passage's first
chapter (or the verse/verse range when the passage starts mid-chapter)."""
import re, json

BOOKS = {
    '창세기': 'GEN', '출애굽기': 'EXO', '레': 'LEV', '민수기': 'NUM', '민': 'NUM', '신': 'DEU', '수': 'JOS',
    '삿': 'JDG', '룻': 'RUT', '삼상': '1SA', '삼하': '2SA', '왕상': '1KI', '왕하': '2KI', '대상': '1CH',
    '대하': '2CH', '라': 'EZR', '느': 'NEH', '더': 'EST', '욥': 'JOB', '시': 'PSA', '잠': 'PRO', '전': 'ECC',
    '아': 'SNG', '사': 'ISA', '렘': 'JER', '애': 'LAM', '겔': 'EZK', '단': 'DAN', '호': 'HOS', '욜': 'JOL',
    '암': 'AMO', '옵': 'OBA', '욘': 'JON', '미': 'MIC', '나': 'NAM', '합': 'HAB', '습': 'ZEP', '학': 'HAG',
    '슥': 'ZEC', '말': 'MAL',
    '마': 'MAT', '막': 'MRK', '눅': 'LUK', '누가복음': 'LUK', '요': 'JHN', '요한복음': 'JHN', '행': 'ACT',
    '사도행전': 'ACT', '롬': 'ROM', '고린도전서': '1CO', '고린도후서': '2CO', '갈': 'GAL', '갈라디아서': 'GAL',
    '엡': 'EPH', '빌': 'PHP', '골': 'COL', '데살로니가전서': '1TH', '데살로니가후서': '2TH', '딤전': '1TI',
    '디모데후서': '2TI', '디도서': 'TIT', '몬': 'PHM', '히': 'HEB', '야고보서': 'JAS', '벧전': '1PE',
    '벧후': '2PE', '요일': '1JN', '요이': '2JN', '요삼': '3JN', '유다서': 'JUD', '계': 'REV',
}
WHOLE_BOOK_ONLY = {'요이', '요삼'}  # one-chapter books written without a number

TOKEN = re.compile(
    r'(?P<solo>요이|요삼)'
    r'|(?P<book>[가-힣]+)?\s*(?P<ch>\d+)(?::(?P<v>\d+))?[a-z]?'
    r'(?P<rng>\s*[~\-]\s*\d+(?::\d+)?)?[a-z]?\s*(?P<unit>[장편])?'
)

def parse(text):
    out, book = [], None
    for m in TOKEN.finditer(text):
        if m.group('solo'):
            book = m.group('solo')
            out.append([book, BOOKS[book] + '.1'])
            continue
        if m.group('book'):
            book = m.group('book')
        assert book in BOOKS, f'unknown book {book!r} in {text!r}'
        ref = f"{BOOKS[book]}.{m.group('ch')}"
        rng = (m.group('rng') or '').replace(' ', '')
        if m.group('v'):
            ref += f".{m.group('v')}"
            end = rng[1:]
            if end and ':' not in end and not m.group('unit'):  # same-chapter verse range (a trailing 장 means the end is a chapter)
                ref += f'-{end}'
        label = f"{book} {m.group('ch')}" + (f":{m.group('v')}" if m.group('v') else '') + rng
        label += m.group('unit') or ('편' if book == '시' else '' if m.group('v') else '장')
        out.append([label, ref])
    return out

readings = {}
for line in open('tools/readings.tsv', encoding='utf8'):
    day, text = line.rstrip('\n').split('\t')
    readings[int(day)] = parse(text)
    assert readings[int(day)], f'day {day}: nothing parsed from {text!r}'

assert sorted(readings) == list(range(1, 366))
open('data/readings.js', 'w', encoding='utf8').write(
    '// Generated by tools/build-readings.py. Day -> [[label, OSIS ref], ...]\nexport default '
    + json.dumps(readings, ensure_ascii=False, separators=(',', ':')) + ';\n')
print(sum(len(v) for v in readings.values()), 'passages')
